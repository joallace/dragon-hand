// Bundles host.mjs with Strudel's packages into one ES module:
//   cd native/strudel/js && npm ci --ignore-scripts && npm run build
// The output is committed; rebuild after changing host.mjs or the versions
// in package.json.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = '../../../presentation/audio/music/strudel_bundle.mjs';
const LICENSES = '../../../presentation/audio/music/strudel_bundle.licenses.txt';
const version = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8')).version;
const packages = ['@strudel/core', '@strudel/mini', '@strudel/tonal', '@strudel/transpiler'];

const result = await build({
  entryPoints: ['host.mjs'],
  outfile: OUT,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2022',
  legalComments: 'inline',
  metafile: true,
  banner: {
    js: [
      '// GENERATED by native/strudel/js/build.mjs: do not edit.',
      `// Contains Strudel (${packages.map((name) => `${name} ${version(name)}`).join(', ')}),`,
      '// https://codeberg.org/uzu/strudel, licensed AGPL-3.0-or-later, and its dependencies,',
      '// together with this game\'s host glue (native/strudel/js/host.mjs).',
    ].join('\n'),
  },
});
const inputs = Object.keys(result.metafile.inputs);
const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`bundled ${inputs.length} modules into ${OUT} (${(bytes / 1024).toFixed(0)} KB)`);
const roots = new Set(inputs.filter((path) => path.startsWith('node_modules/'))
  .map((path) => path.split('/').slice(1, path.split('/')[1].startsWith('@') ? 3 : 2).join('/')));
// What the bundle contains, for the people it is distributed to.
const lines = [...roots].sort().map((name) => {
  const info = JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8'));
  const repo = typeof info.repository === 'string' ? info.repository : (info.repository?.url ?? info.homepage ?? '');
  return `${name} ${info.version} - ${info.license ?? 'see package'} - ${repo}`;
});
writeFileSync(LICENSES, [
  'strudel_bundle.mjs contains these packages (generated by native/strudel/js/build.mjs).',
  'Strudel is AGPL-3.0-or-later: see strudel_bundle.LICENSE.txt. The bundle is unminified source;',
  'the build inputs are native/strudel/js/ (host.mjs, package.json, package-lock.json).',
  '',
  ...lines,
  '',
].join('\n'));
console.log(`${lines.length} packages listed in ${LICENSES}`);
